-- V41__create_member_profile_tables.sql (확장 단계, BE-140 · ERD v1.50)
-- 로그인 전용이 된 사용자 데이터의 회원 키 테이블. 칸 · 제약은 익명 ID 테이블(V22 · V23 · V29 · V30 · V35 · V36)과 같고 주인만 회원이다.
-- 기존 익명 데이터는 옮기지 않는다(BE-140 결정: 체험만 이관하고 나머지는 초기화). 옛 테이블은 쓰지 않고 두었다가 후속 이슈에서 지운다.
-- 테이블 추가뿐이라 BE-60 "main으로 가는 마이그레이션은 추가만" 규칙에 맞는다(지금 앱은 이 테이블을 모른다).
-- 다른 점은 FK 삭제 동작뿐이다: 회원 FK는 ON DELETE CASCADE로, 회원에 딸린 기록이라 회원이 지워지면 함께 지운다(V35 익명 쪽과 같은 이유,
-- V22 · V23 · V29 · V30의 익명 FK는 기본 NO ACTION). 체험 · 성향 결과 · 커뮤니티의 회원 FK는 NO ACTION이라, 회원 탈퇴를 만들 때 그 행들을 먼저 정리해야 한다

-- 출석 (V22 attendance)
CREATE TABLE member_attendance (
    member_id   bigint      NOT NULL,
    attended_on date        NOT NULL,                 -- 서버가 정한 출석 날짜(V22와 같은 기준)
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_member_attendance PRIMARY KEY (member_id, attended_on),
    CONSTRAINT fk_member_attendance_member FOREIGN KEY (member_id) REFERENCES member (id) ON DELETE CASCADE
);

-- 카드 꾸미기 · 책갈피 (V23 profile_deco). 값 검사는 서버 코드가 한다(V23과 같다)
CREATE TABLE member_profile_deco (
    member_id           bigint       NOT NULL,
    portrait            varchar(200) NOT NULL,
    frame               varchar(30)  NOT NULL,
    background          varchar(30)  NOT NULL,
    sash_style          varchar(30)  NOT NULL,
    sash_color_short    varchar(30)  NOT NULL,
    sash_color_long     varchar(30)  NOT NULL,
    sash_icon_left      varchar(30)  NOT NULL,
    sash_icon_right     varchar(30)  NOT NULL,
    bookmark_character  varchar(30)  NOT NULL,
    bookmark_face       varchar(30)  NOT NULL,
    bookmark_face_style varchar(30)  NOT NULL,
    bookmark_color      varchar(30)  NOT NULL,
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_member_profile_deco PRIMARY KEY (member_id),
    CONSTRAINT fk_member_profile_deco_member FOREIGN KEY (member_id) REFERENCES member (id) ON DELETE CASCADE
);

-- 공개 카드 · 카드 아래 줄 · 한 줄 소개 (V29 profile_setting + V36 card_line · card_level)
CREATE TABLE member_profile_setting (
    member_id         bigint      NOT NULL,
    shown_card        varchar(10) NOT NULL DEFAULT 'current',
    profile_card_type varchar(10) NOT NULL DEFAULT 'current',
    bio               varchar(40) NOT NULL DEFAULT '',
    card_line         varchar(10) NOT NULL DEFAULT 'type',
    card_level        boolean     NOT NULL DEFAULT false,
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_member_profile_setting PRIMARY KEY (member_id),
    CONSTRAINT fk_member_profile_setting_member FOREIGN KEY (member_id) REFERENCES member (id) ON DELETE CASCADE,
    CONSTRAINT chk_member_profile_setting_shown_card CHECK (shown_card IN ('initial', 'retake', 'current')),
    CONSTRAINT chk_member_profile_setting_profile_card_type CHECK (profile_card_type IN ('initial', 'retake', 'current')),
    CONSTRAINT chk_member_profile_setting_bio CHECK (bio = btrim(bio) AND bio !~ '[\r\n]'),
    CONSTRAINT chk_member_profile_setting_card_line CHECK (card_line IN ('type', 'signature', 'job'))
);

-- 경험치 기록 (V30 xp_event)
CREATE TABLE member_xp_event (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY,
    member_id  bigint      NOT NULL,
    source     varchar(20) NOT NULL,
    ref_key    varchar(80) NOT NULL,                  -- 같은 대상으로 두 번 받지 않게 하는 키(BE-106 XpSource 규칙)
    group_key  varchar(80) NOT NULL DEFAULT '',
    amount     int         NOT NULL,
    awarded_on date        NOT NULL,                  -- 일일 상한을 세는 KST 날짜(V30과 같다)
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_member_xp_event PRIMARY KEY (id),
    CONSTRAINT fk_member_xp_event_member FOREIGN KEY (member_id) REFERENCES member (id) ON DELETE CASCADE,
    CONSTRAINT uq_member_xp_event_ref UNIQUE (member_id, source, ref_key),
    CONSTRAINT chk_member_xp_event_source CHECK (source IN ('POST', 'SHARE_POST', 'COMMENT', 'LIKE_GIVEN', 'LIKE_RECEIVED', 'SNS_SHARE')),
    CONSTRAINT chk_member_xp_event_amount CHECK (amount > 0)
);
CREATE INDEX ix_member_xp_event_day ON member_xp_event (member_id, source, awarded_on);
CREATE INDEX ix_member_xp_event_group ON member_xp_event (member_id, source, group_key);

-- 카드에 보일 직업 (V30 profile_job)
CREATE TABLE member_profile_job (
    member_id  bigint      NOT NULL,
    job        varchar(30) NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_member_profile_job PRIMARY KEY (member_id),
    CONSTRAINT fk_member_profile_job_member FOREIGN KEY (member_id) REFERENCES member (id) ON DELETE CASCADE,
    CONSTRAINT chk_member_profile_job_job CHECK (job IN ('NONE', 'LAW_STUDENT', 'TRAINEE', 'PROBATION_JUDGE', 'JUDGE', 'PRESIDING_JUDGE',
        'HIGH_COURT_JUDGE', 'DISTRICT_COURT_CHIEF', 'HIGH_COURT_CHIEF', 'JUSTICE', 'CHIEF_JUSTICE'))
);

-- 일러스트 · 의상 수집 (V35 collection_item). kind는 CHECK 없이 서버 코드가 검사한다(V35와 같다)
CREATE TABLE member_collection_item (
    member_id   bigint      NOT NULL,
    kind        varchar(20) NOT NULL,
    item_id     varchar(64) NOT NULL,
    case_id     bigint      NOT NULL,
    acquired_at timestamptz NOT NULL DEFAULT now(),
    seen_at     timestamptz,
    CONSTRAINT pk_member_collection_item PRIMARY KEY (member_id, kind, item_id),
    CONSTRAINT fk_member_collection_item_member FOREIGN KEY (member_id) REFERENCES member (id) ON DELETE CASCADE,
    CONSTRAINT fk_member_collection_item_legal_case FOREIGN KEY (case_id) REFERENCES legal_case (id) ON DELETE CASCADE
);
CREATE INDEX idx_member_collection_item_case ON member_collection_item (member_id, case_id, kind);

-- 도전과제 해금 기록 (V35 achievement_unlock). 옛 기록은 옮기지 않는다 — 체험 결과를 다시 보면 다시 판정해 남긴다(BE-140 결정)
CREATE TABLE member_achievement_unlock (
    member_id      bigint      NOT NULL,
    achievement_id varchar(40) NOT NULL,
    unlocked_at    timestamptz NOT NULL DEFAULT now(),
    seen_at        timestamptz,
    CONSTRAINT pk_member_achievement_unlock PRIMARY KEY (member_id, achievement_id),
    CONSTRAINT fk_member_achievement_unlock_member FOREIGN KEY (member_id) REFERENCES member (id) ON DELETE CASCADE
);
