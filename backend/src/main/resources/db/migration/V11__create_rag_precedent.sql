-- AI 판결 RAG 판례 저장소 (BE-51). 결정: docs/ai-judgment-pipeline.md 8-1 (COMMON-21), 수집: docs/rag-precedent-sources.md (BE-50)
-- 오프라인 파이프라인(generate의 유사 판례 검색, BE-54)이 쓰는 내부 테이블이다. 사용자 API에서는 조회하지 않는다.
-- 행은 비공개 저장소 시드(R__40)가 넣는다. 이 파일은 구조만 만든다.
--   facts_summary     = 검색 기준. 비식별화한 사실관계 요약이고, 임베딩 입력은 이 칸뿐이다
--   sentencing_reason = 프롬프트에 넣는 본문. 비식별화한 양형 이유
--   판결문 원문 · 사건번호 · 법원명은 저장하지 않는다. 사건번호는 자기 사건 제외용 해시(SHA-256)만 둔다
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE rag_precedent (
    id                 bigint       GENERATED BY DEFAULT AS IDENTITY,
    source             varchar(20)  NOT NULL,  -- LAW_GO_KR(법제처 국가법령정보센터) / LBOX(LBox Open, CC BY-NC)
    source_ref         varchar(50)  NOT NULL,  -- 출처 안의 ID (판례일련번호 · LBox id). 다시 받을 때 같은 판례를 찾는 값
    case_number_hash   char(64),               -- 사건번호(공백 제거) SHA-256 hex. LBox는 사건번호가 없어 NULL
    case_group         varchar(50)  NOT NULL,  -- 같은 사건(1심 · 항소심 · 공범 별도 판결 · 병합) 묶음 ID
    crime_type         varchar(20)  NOT NULL,  -- legal_case.crime_type과 같은 값
    charge_name        varchar(200),           -- 죄명 (예: 살인, 살인미수)
    statutes           jsonb,                  -- 적용 법조문 (예: ["형법 제250조 제1항"])
    court_level        varchar(20)  NOT NULL,
    decided_at         date,                   -- 선고일. LBox는 본문에 없어 NULL
    incident_date      date,                   -- 사건 발생일 (자동 추정, flags.checks에 의심 사유)
    guideline_id       bigint,                 -- 적용 양형기준 버전. 시행 전 · DB에 없는 버전(2009 최초)이면 NULL
    penalty_type       varchar(20),            -- 주문 형량 (judgment.penalty_type과 같은 값)
    prison_months      int,
    suspension_months  int,
    fine_amount        bigint,
    recommended_range  jsonb,                  -- 양형기준 권고 범위. 양형기준 데이터화 뒤 채운다 (지금은 NULL)
    sentencing_factors jsonb,                  -- 양형인자 {"aggravating": [...], "mitigating": [...]}
    facts_summary      text         NOT NULL,
    sentencing_reason  text         NOT NULL,
    embedding          vector(3072) NOT NULL,  -- facts_summary 임베딩 (task type RETRIEVAL_DOCUMENT)
    embedding_model    varchar(50)  NOT NULL,  -- 예: gemini-embedding-001
    embedding_dim      int          NOT NULL,
    on_hold            boolean      NOT NULL DEFAULT false,  -- 사용 보류. true면 검색에서 뺀다(행은 남긴다)
    hold_reason        text,                                  -- 보류 사유 (예: LBox 라이선스 확인 전)
    flags              jsonb        NOT NULL DEFAULT '{}'::jsonb,
    -- 자동 판정 표시. 예: {"verified": false, "checks": ["발생일과 선고일이 3년 넘게 차이 남"],
    --   "partlyAcquitted": true, "concurrent": true, "beforePenaltyRevision": true}
    -- verified = 사람이 확인했는지. 팀 결정(2026-10-10)으로 확인 없이 전부 넣어 지금은 모두 false다
    created_at         timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_rag_precedent PRIMARY KEY (id),
    CONSTRAINT uk_rag_precedent_source UNIQUE (source, source_ref),
    CONSTRAINT fk_rag_precedent_guideline FOREIGN KEY (guideline_id) REFERENCES sentencing_guideline (id),
    CONSTRAINT chk_rag_precedent_source CHECK (source IN ('LAW_GO_KR', 'LBOX')),
    CONSTRAINT chk_rag_precedent_crime_type CHECK (crime_type IN ('MURDER', 'FRAUD', 'INJURY')),
    CONSTRAINT chk_rag_precedent_court_level CHECK (court_level IN ('FIRST', 'APPEAL')),
    CONSTRAINT chk_rag_precedent_case_number_hash CHECK (case_number_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_rag_precedent_penalty_type CHECK (penalty_type IN ('DEATH', 'LIFE', 'PRISON', 'FINE')),
    CONSTRAINT chk_rag_precedent_embedding_dim CHECK (embedding_dim = vector_dims(embedding)),
    CONSTRAINT chk_rag_precedent_text CHECK (btrim(facts_summary) <> '' AND btrim(sentencing_reason) <> ''),
    CONSTRAINT chk_rag_precedent_hold CHECK (
        (NOT on_hold AND hold_reason IS NULL) OR (on_hold AND btrim(coalesce(hold_reason, '')) <> ''))
);

CREATE INDEX idx_rag_precedent_case_group ON rag_precedent (case_group);
CREATE INDEX idx_rag_precedent_case_number_hash ON rag_precedent (case_number_hash);
-- 판례가 수백 건인 동안 벡터 인덱스 없이 전체를 비교한다(8-1). 수만 건이면 halfvec(3072) + HNSW로 바꾼다

-- 유사 판례 검색 (자기 사건 제외). 코사인 유사도 = 1 - 코사인 거리(<=>)
--   exclude_hashes: 판결하려는 사건의 사건번호 해시들(1심 · 항소심). 그 해시가 있는 사건 그룹 전체를 뺀다
--   exclude_groups: 직접 뺄 사건 그룹 (같은 사건의 다른 심급 · 공범 별도 판결 · 병합 사건을 알고 있을 때). NULL 원소는 무시한다
--   (NOT IN에 NULL이 섞이면 모든 행이 빠져 결과가 조용히 비므로 NOT EXISTS로 비교한다)
--   같은 사건 그룹은 가장 비슷한 판례 1건만 돌려준다 (검색 결과에 같은 사건이 두 번 나오지 않게)
--   사용 보류(on_hold) 판례는 결과에서 뺀다. 자기 사건 제외는 보류 판례의 사건번호 해시도 그대로 본다
CREATE FUNCTION rag_precedent_search(
    query          vector(3072),
    crime          varchar,
    exclude_hashes text[],
    exclude_groups text[],
    top_k          int,
    min_score      double precision
) RETURNS TABLE (precedent_id bigint, case_group varchar, score double precision)
LANGUAGE sql STABLE AS $$
    WITH excluded AS (
        SELECT p.case_group FROM rag_precedent p WHERE p.case_number_hash = ANY (coalesce(exclude_hashes, '{}'))
        UNION
        SELECT g FROM unnest(coalesce(exclude_groups, '{}')) AS g WHERE g IS NOT NULL
    ), scored AS (
        SELECT DISTINCT ON (p.case_group) p.id, p.case_group, 1 - (p.embedding <=> query) AS score
        FROM rag_precedent p
        WHERE p.crime_type = crime
          AND NOT p.on_hold
          AND NOT EXISTS (SELECT 1 FROM excluded e WHERE e.case_group = p.case_group)
        ORDER BY p.case_group, p.embedding <=> query, p.id
    )
    SELECT s.id, s.case_group, s.score FROM scored s
    WHERE s.score >= min_score
    ORDER BY s.score DESC, s.id
    LIMIT top_k
$$;
