    'CASE_PHOTO_UPLOAD', 'CASE_PHOTO_DELETE', 'CASE_PAPER_GENERATE', 'CASE_PAPER_UPDATE',
    'CASE_IMPORT', 'CASE_IMPORT_LOAD',
    'CASE_SCRIPT_APPROVE', 'CASE_SCRIPT_REJECT', 'CASE_SCRIPT_UPDATE'));
