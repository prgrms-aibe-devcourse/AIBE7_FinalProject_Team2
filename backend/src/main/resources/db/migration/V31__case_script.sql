-- V31__case_script.sql
-- 사건 대본 적재 · 검수 (BE-108). BE-107이 파이프라인에서 만든 증거조사 대사를 사건에 붙이고,
-- 관리자가 검수해 승인한 것만 공개한다(공개 서빙은 BE-109).
--
-- 표를 따로 두는 이유: 대본은 사건 내용(case_section · factor)과 생애주기가 다르다. 사건이 공개된
-- 뒤에 대본만 늦게 들어오거나(FE-33 수작업), 대본만 반려돼 다시 만들 수 있다. legal_case에 칸을
-- 더하면 "사건은 공개인데 대본은 검수 중"을 나타낼 자리가 없다.
--
-- 내용을 jsonb 한 칸에 두는 이유: 서버는 대본 안을 들여다보지 않는다(검색 · 집계 대상이 아니다).
-- 형식을 정하는 쪽은 파이프라인이고, 칸으로 펼쳐 적으면 파이프라인이 필드를 늘릴 때마다 스키마가
-- 따라 깨진다 — case_paper.article(V21)과 같은 관례다.
--
-- 칸 이름을 acts가 아니라 evidence로 둔 이유: BE-107이 만드는 것은 **증거조사 대사뿐**이다.
-- 1막 기사 해설 · 피고인신문 · 최종의견은 범위 밖이고(COMMON-65 · FE-33), 아직 없는 구조를 미리
-- 만들어 두면 나중에 실제 형식과 어긋난다. 공개 응답 모양은 BE-109에서 FE-33과 정한다.

CREATE TABLE case_script (
    id                   bigint       GENERATED BY DEFAULT AS IDENTITY,
    case_id              bigint       NOT NULL,
    evidence             jsonb        NOT NULL,  -- 판단 요소별 대사 배열 (파이프라인 evidence.json의 evidence)
    model                varchar(100),            -- 어느 모델로 만들었는지 (예: google:gemini-2.5-flash)
    generated_at         timestamptz,             -- 파이프라인이 대본을 만든 시각(적재 시각 created_at과 다르다)
    -- 호출 한도로 중간에 멈췄는지. publishable이 false일 때 "생성 실패"인지 "중단"인지 구분하는 값이다 —
    -- 관리자가 다시 생성할지 판단하는 근거라 따로 둔다(실패한 줄은 evidence의 text가 null이라 셀 수 있다)
    stopped              boolean      NOT NULL DEFAULT false,
    cast_roles           jsonb,                   -- 배역 {prosecutor, defense}. cast는 SQL 예약어라 이름을 바꿨다
    -- 검사 · 변호인 분량이 치우쳤다는 경고 (있으면 검수 화면에 보인다). 길이를 제한하지 않는 이유:
    -- 모델이 만든 문장이 들어오는 칸을 varchar로 두면 한 번 넘칠 때 적재 전체가 막힌다(BE-93 1차에서 겪음)
    balance_warning      text,
    -- 파이프라인이 "증거 카드와 대사가 1:1로 어긋난다"고 표시한 결과(생성 실패 · 호출 한도 중단).
    -- false면 승인할 수 없다 — 다시 생성해야 한다 (BE-107 PR #277 리뷰 7번의 계약)
    publishable          boolean      NOT NULL,
    -- 검수 상태. judgment(V16)와 같은 방식으로 APPROVED · REJECTED만 저장하고, 비어 있으면 PENDING으로 읽는다
    review_status        varchar(20),
    reviewed_by_admin_id bigint,
    reviewed_at          timestamptz,
    review_note          varchar(500),            -- 반려 사유. 관리자가 쓰는 칸이라 judgment(V16)와 같은 길이로 둔다
    created_at           timestamptz  NOT NULL DEFAULT now(),
    updated_at           timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_case_script PRIMARY KEY (id),
    CONSTRAINT fk_case_script_legal_case FOREIGN KEY (case_id) REFERENCES legal_case (id),
    CONSTRAINT fk_case_script_admin FOREIGN KEY (reviewed_by_admin_id) REFERENCES admin_account (id) ON DELETE SET NULL,
    -- 사건마다 대본은 1건 (case_paper와 같다). 다시 생성해 덮어쓰는 경로는 아직 없다 — 적재는 사건을
    -- 새로 만들기 때문이다. 대본만 다시 만드는 기능이 생기면 이 제약 덕에 행이 둘로 늘지 않는다
    CONSTRAINT uk_case_script_case_id UNIQUE (case_id),
    CONSTRAINT chk_case_script_review_status CHECK (review_status IS NULL OR review_status IN ('APPROVED', 'REJECTED')),
    -- 승인하려면 파이프라인이 공개 가능하다고 한 결과여야 한다. 데이터로도 막아 둔다
    CONSTRAINT chk_case_script_publishable_approved CHECK (review_status <> 'APPROVED' OR publishable),
    -- 사유는 반려에만 둔다 (judgment V16과 같은 기준)
    CONSTRAINT chk_case_script_review_note CHECK (review_note IS NULL OR review_status = 'REJECTED')
);

