-- 오프라인 파이프라인(generate의 발생 시점 양형기준 검색, BE-54)이 쓰는 내부 테이블이다. 사용자 API에서는 조회하지 않는다.
-- 행은 비공개 시드 R__41(공개 저장소 tools/sentencing-guideline/store.py sql 출력)이 넣는다. 이 파일은 구조만 만든다.
--   조각 = 양형기준 한 버전 × 한 섹션 × 한 유형(또는 인자 행 · 정의 항목). 범죄 유형이 늘면 행만 늘고 구조는 그대로다
--   content    = 프롬프트에 넣는 본문
--   embed_text = 임베딩 입력. 본문 앞에 "[범죄 · 버전(시행 기간) · 섹션 · 대상]" 머리말을 붙인 것
--   meta       = 바로 찾기용 구조 값 (형량범위 {"range": {"감경","기본","가중"}}, 양형인자 {"factorPath", "감경요소", "가중요소"} 등)

-- 버전 이름은 시드(R__10 · R__41)가 이름으로 찾아 넣으므로 범죄 유형 안에서 겹치면 안 된다
ALTER TABLE sentencing_guideline
    ADD CONSTRAINT uk_sentencing_guideline_version UNIQUE (crime_category, version_name);

CREATE TABLE rag_guideline (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY,
    guideline_id    bigint       NOT NULL,  -- 양형기준 버전 (sentencing_guideline)
    chunk_key       varchar(60)  NOT NULL,  -- 조각 ID (예: 살인-2013-05-15-001). R__41이 통째로 다시 넣을 때마다 같은 값
    section         varchar(30)  NOT NULL,  -- 형량범위 / 양형인자 / 유형의 정의 / 양형인자의 정의 / 집행유예 참작사유 등 (사이트 탭 이름)
    subject         varchar(200),           -- 섹션 안의 대상 (예: 제2유형 보통 동기 살인, 특별양형인자 > 행위 > 공통)
    type_no         int,                    -- 형량범위 조각의 유형 번호
    content         text         NOT NULL,
    embed_text      text         NOT NULL,
    meta            jsonb        NOT NULL DEFAULT '{}'::jsonb,
    embedding       vector(3072) NOT NULL,  -- embed_text 임베딩 (task type RETRIEVAL_DOCUMENT)
    embedding_model varchar(50)  NOT NULL,  -- 예: gemini-embedding-001
    embedding_dim   int          NOT NULL,
    source_url      varchar(300),
    created_at      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_rag_guideline PRIMARY KEY (id),
    CONSTRAINT uk_rag_guideline_chunk_key UNIQUE (chunk_key),
    CONSTRAINT fk_rag_guideline_guideline FOREIGN KEY (guideline_id) REFERENCES sentencing_guideline (id),
    CONSTRAINT chk_rag_guideline_embedding_dim CHECK (embedding_dim = vector_dims(embedding)),
    CONSTRAINT chk_rag_guideline_text CHECK (btrim(content) <> '' AND btrim(embed_text) <> '')
);

CREATE INDEX idx_rag_guideline_guideline_section ON rag_guideline (guideline_id, section);
-- 버전 하나에 조각 수십 개라 벡터 인덱스 없이 버전으로 거른 뒤 전체를 비교한다

-- 기준일에 시행 중이던 양형기준 버전. 기준일(공소제기일 또는 대신 쓰는 날짜)을 정하는 것은 호출하는 쪽이다 (BE-52 · BE-54)
--   조각이 적재된 버전만 본다. 개발용 시드의 '가상 예시 버전'처럼 내용 없는 버전이 끼어들지 않게 하려는 것
--   기준일이 NULL이거나 최초 시행일 전이면 NULL (양형기준 없음)
CREATE FUNCTION sentencing_guideline_at(category varchar, at date) RETURNS bigint
LANGUAGE sql STABLE AS $$
    SELECT g.id FROM sentencing_guideline g
    WHERE g.crime_category = category
      AND g.effective_date <= at
      AND EXISTS (SELECT 1 FROM rag_guideline r WHERE r.guideline_id = g.id)
    ORDER BY g.effective_date DESC, g.id DESC
    LIMIT 1
$$;

-- 버전 안 의미 검색. 코사인 유사도 = 1 - 코사인 거리(<=>)
--   sections: 찾을 섹션 (NULL이면 전체). 형량범위처럼 구조가 정해진 값은 검색 대신 section · type_no로 바로 읽는다
CREATE FUNCTION rag_guideline_search(
    query     vector(3072),
    guideline bigint,
    sections  varchar[],
    top_k     int,
    min_score double precision
) RETURNS TABLE (chunk_id bigint, section varchar, score double precision)
LANGUAGE sql STABLE AS $$
    SELECT r.id, r.section, 1 - (r.embedding <=> query) AS score
    FROM rag_guideline r
    WHERE r.guideline_id = guideline
      AND (sections IS NULL OR r.section = ANY (sections))
      AND 1 - (r.embedding <=> query) >= min_score
    ORDER BY r.embedding <=> query, r.id
    LIMIT top_k
$$;
