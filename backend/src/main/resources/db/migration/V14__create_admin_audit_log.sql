-- V14__create_admin_audit_log.sql
-- 관리자 감사 로그 (확장 단계, BE-68 · WBS 7.4.5). 관리자가 "누가 · 언제 · 무엇을" 했는지 남긴다.
-- 로그인 성공 · 실패 · 로그아웃, 원본 판결문 열람(A-7), 검수 API(A-9 ~ A-13)가 쓴다.
-- 비밀번호 · 원문 내용 · 토큰은 넣지 않는다. detail에는 반려 사유 · 바꾼 필드 이름처럼 판단에 필요한 값만 둔다.
-- admin_id는 계정이 지워져도 기록이 남도록 ON DELETE SET NULL이고, 누구였는지는 actor_email(그때의 이메일)로 남는다.
CREATE TABLE admin_audit_log (
    id          bigint       GENERATED BY DEFAULT AS IDENTITY,
    admin_id    bigint,
    actor_email varchar(254),
    action      varchar(30)  NOT NULL,
    target_type varchar(20),
    target_id   bigint,
    detail      jsonb,
    ip_address  varchar(45),
    created_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_admin_audit_log PRIMARY KEY (id),
    CONSTRAINT fk_admin_audit_log_admin FOREIGN KEY (admin_id) REFERENCES admin_account (id) ON DELETE SET NULL,
    CONSTRAINT chk_admin_audit_log_action CHECK (action IN (
        'LOGIN_SUCCESS', 'LOGIN_FAILURE', 'LOGOUT', 'SOURCE_VIEW',
        'JUDGMENT_APPROVE', 'JUDGMENT_REJECT', 'CASE_UPDATE', 'VALUE_AXIS_CONFIRM', 'CASE_PUBLISH')),
    CONSTRAINT chk_admin_audit_log_target_type CHECK (target_type IS NULL OR target_type IN ('CASE', 'JUDGMENT', 'FACTOR', 'CASE_SOURCE')),
    CONSTRAINT chk_admin_audit_log_target CHECK ((target_type IS NULL) = (target_id IS NULL)),
    CONSTRAINT chk_admin_audit_log_email_lower CHECK (actor_email = lower(actor_email))
);

-- "관리자 N이 한 일" · "이 사건 · 판결에 누가 손댔나"를 최근 순으로 찾는다
CREATE INDEX ix_admin_audit_log_admin_created ON admin_audit_log (admin_id, created_at DESC);
CREATE INDEX ix_admin_audit_log_target ON admin_audit_log (target_type, target_id, created_at DESC);
CREATE INDEX ix_admin_audit_log_created ON admin_audit_log (created_at DESC);
