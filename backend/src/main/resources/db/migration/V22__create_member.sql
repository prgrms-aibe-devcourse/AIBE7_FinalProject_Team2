-- 회원: 카카오 로그인으로 만든다. 개인정보는 받지 않고 공급자 회원번호만 저장한다(카카오 동의항목 없음)

CREATE TABLE member (
    id               bigint      GENERATED BY DEFAULT AS IDENTITY,
    provider         varchar(20) NOT NULL,                  -- 로그인 공급자. 지금은 KAKAO만
    provider_user_id varchar(64) NOT NULL,                  -- 공급자의 회원번호(카카오 id)
    created_at       timestamptz NOT NULL DEFAULT now(),
    last_login_at    timestamptz,
    CONSTRAINT pk_member PRIMARY KEY (id),
    CONSTRAINT uq_member_provider_user UNIQUE (provider, provider_user_id),
    CONSTRAINT ck_member_provider CHECK (provider IN ('KAKAO'))
);

-- 익명 기록 → 회원 연결 (V3에서는 member 테이블이 없어 FK를 두지 않았다). 지금 연결된 행은 없어 그대로 건다
ALTER TABLE anonymous_user
    ADD CONSTRAINT fk_anonymous_user_member FOREIGN KEY (member_id) REFERENCES member (id);

-- 회원 1 : 익명 N 조회용 (연결된 행만)
CREATE INDEX ix_anonymous_user_member ON anonymous_user (member_id) WHERE member_id IS NOT NULL;
