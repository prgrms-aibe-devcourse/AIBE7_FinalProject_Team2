-- 신문 지면 콘텐츠 (BE-92, COMMON-41). 사건마다 1건, PR #138 script.json의 paper 필드(headline · deck ·
-- photo · caption · article · extraPhotos) 중 Gemini가 짓는 부분(headline · deck · caption · article)만
-- 저장한다. photo는 legal_case.thumbnail_url을, extraPhotos는 case_incident_photo(BE-91)를 그대로
-- 재사용한다 — 같은 사진을 두 군데에 중복 저장하지 않는다(BE-78 문의 답변, docs/decisions/BE-92.md).
CREATE TABLE case_paper (
    id         bigint       GENERATED BY DEFAULT AS IDENTITY,
    case_id    bigint       NOT NULL,
    desk       varchar(50)  NOT NULL,  -- 지면 섹션명 (예: 사회면). 지금은 고정값, 범죄 유형별 분류는 후속
    headline   varchar(200) NOT NULL,
    deck       varchar(300),
    caption    varchar(200),
    article    jsonb        NOT NULL,  -- 본문 문단 배열 (keywords 등과 같은 jsonb 배열 관례)
    created_at timestamptz  NOT NULL DEFAULT now(),
    updated_at timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_case_paper PRIMARY KEY (id),
    CONSTRAINT fk_case_paper_legal_case FOREIGN KEY (case_id) REFERENCES legal_case (id),
    -- 사건마다 신문 지면은 1건 (재생성은 있는 행을 덮어쓴다)
    CONSTRAINT uk_case_paper_case_id UNIQUE (case_id)
);

