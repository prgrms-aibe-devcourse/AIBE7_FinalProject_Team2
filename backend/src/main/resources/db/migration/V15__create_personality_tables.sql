-- V15__create_personality_tables.sql
-- 판결 성향 테스트 / 체험 기여 저장 구조 (BE-69, WBS 7.6.3).
-- docs/personality-scoring.md v0.4 및 docs/personality-test-content.md 기준.
-- 문항·선택지·유형 콘텐츠 시드는 별도 검토 후 추가한다.
-- 문항은 상황 문장 + 두 행동(A · B) 문장을 갖고, 5칸(매우 A · 조금 A · 보통 · 조금 B · 매우 B)의 "매우 · 조금 · 보통"은 화면이 붙인다.
-- 그래서 선택지 행에는 문구가 없고 글자 · 점수 · 순서만 있다.
-- 타입은 다른 테이블과 같게 varchar · int를 쓴다(char · smallint는 JPA 스키마 검증에서 어긋나기 쉽다).
-- 유형 코드(INTP 등)는 내부 데이터로만 쓰고 화면 · 공유 주소에는 쓰지 않는다(상표 우려, #119). 공유 주소는 share_id다.

CREATE TABLE personality_question (
    id            bigint       GENERATED BY DEFAULT AS IDENTITY,
    axis          varchar(20)  NOT NULL,
    scenario      varchar(20)  NOT NULL,
    content       text         NOT NULL,   -- 상황 문장
    option_a      text         NOT NULL,   -- 왼쪽 끝 행동 문장 (매우 A · 조금 A)
    option_b      text         NOT NULL,   -- 오른쪽 끝 행동 문장 (조금 B · 매우 B)
    display_order int          NOT NULL,
    is_active     boolean      NOT NULL DEFAULT true,
    CONSTRAINT pk_personality_question PRIMARY KEY (id),
    CONSTRAINT uk_personality_question_id_axis UNIQUE (id, axis),
    CONSTRAINT uk_personality_question_display_order UNIQUE (display_order),
    CONSTRAINT chk_personality_question_axis CHECK (axis IN (
        'APOLOGY_SINCERITY', 'FAULT_STANDARD', 'PRINCIPLE_RELATION', 'ORDER_OPPORTUNITY')),
    CONSTRAINT chk_personality_question_scenario CHECK (scenario IN ('FRIEND', 'FAMILY', 'WORK', 'NEIGHBOR')),
    CONSTRAINT chk_personality_question_order CHECK (display_order > 0),
    CONSTRAINT chk_personality_question_content CHECK (length(btrim(content)) > 0),
    CONSTRAINT chk_personality_question_options CHECK (length(btrim(option_a)) > 0 AND length(btrim(option_b)) > 0)
);

CREATE TABLE personality_choice (
    id            bigint      GENERATED BY DEFAULT AS IDENTITY,
    question_id   bigint      NOT NULL,
    axis          varchar(20) NOT NULL,
    letter        varchar(1),
    score         int         NOT NULL,
    display_order int         NOT NULL,
    CONSTRAINT pk_personality_choice PRIMARY KEY (id),
    CONSTRAINT fk_personality_choice_question_axis FOREIGN KEY (question_id, axis)
        REFERENCES personality_question (id, axis),
    CONSTRAINT uk_personality_choice_question_order UNIQUE (question_id, display_order),
    CONSTRAINT chk_personality_choice_order CHECK (display_order BETWEEN 1 AND 5),
    CONSTRAINT chk_personality_choice_letter CHECK (
        (letter IS NULL AND score = 0)
        OR (letter IS NOT NULL AND score IN (1, 2) AND (
               (axis = 'APOLOGY_SINCERITY'  AND letter IN ('E', 'I'))
            OR (axis = 'FAULT_STANDARD'     AND letter IN ('S', 'N'))
            OR (axis = 'PRINCIPLE_RELATION' AND letter IN ('T', 'F'))
            OR (axis = 'ORDER_OPPORTUNITY'  AND letter IN ('J', 'P'))))
    )
);
CREATE INDEX ix_personality_choice_question_id ON personality_choice (question_id);

CREATE TABLE personality_type (
    code                   varchar(4)   NOT NULL,   -- 내부 코드. 화면 · 공유 주소에는 쓰지 않는다
    share_id               varchar(16)  NOT NULL,   -- 공유 주소 /test/types/{share_id}. 시드로 고정하고 바꾸지 않는다(공유된 링크가 깨짐)
    name                   varchar(100) NOT NULL,   -- 유형명 (예: 그럴 수도 있지형)
    character_code         varchar(10)  NOT NULL,   -- 캐릭터 (NAERO 내로 · NAMBUL 남불). character는 SQL 예약어라 피한다
    one_liner              text         NOT NULL,
    meme                   varchar(100) NOT NULL,   -- 밈 문구 (결과 카드 UI 텍스트)
    daily_description      text         NOT NULL,   -- ① 일상 가치관
    verdict_description    text         NOT NULL,   -- ② 판결 연계
    tolerance              int          NOT NULL,
    image_url              varchar(500),
    CONSTRAINT pk_personality_type PRIMARY KEY (code),
    CONSTRAINT uk_personality_type_share_id UNIQUE (share_id),
    CONSTRAINT chk_personality_type_share_id CHECK (share_id ~ '^[A-Za-z0-9]{6,16}$'),
    CONSTRAINT chk_personality_type_code CHECK (
        char_length(code) = 4 AND
        substring(code FROM 1 FOR 1) IN ('E', 'I') AND
        substring(code FROM 2 FOR 1) IN ('S', 'N') AND
        substring(code FROM 3 FOR 1) IN ('T', 'F') AND
        substring(code FROM 4 FOR 1) IN ('J', 'P')),
    CONSTRAINT chk_personality_type_character CHECK (character_code IN ('NAERO', 'NAMBUL')),
    CONSTRAINT chk_personality_type_tolerance CHECK (
        tolerance = (CASE WHEN substring(code FROM 1 FOR 1) = 'I' THEN 1 ELSE 0 END)
                  + (CASE WHEN substring(code FROM 2 FOR 1) = 'N' THEN 1 ELSE 0 END)
                  + (CASE WHEN substring(code FROM 3 FOR 1) = 'F' THEN 1 ELSE 0 END)
                  + (CASE WHEN substring(code FROM 4 FOR 1) = 'P' THEN 1 ELSE 0 END)),
    CONSTRAINT chk_personality_type_name CHECK (length(btrim(name)) > 0),
    CONSTRAINT chk_personality_type_one_liner CHECK (length(btrim(one_liner)) > 0),
    CONSTRAINT chk_personality_type_texts CHECK (
        length(btrim(meme)) > 0 AND length(btrim(daily_description)) > 0 AND length(btrim(verdict_description)) > 0)
);

CREATE TABLE personality_result (
    id                bigint       GENERATED BY DEFAULT AS IDENTITY,
    anonymous_user_id uuid         NOT NULL,
    type_code         varchar(4)   NOT NULL,
    axis_scores       jsonb        NOT NULL,
    answers           jsonb        NOT NULL,
    is_current        boolean      NOT NULL DEFAULT true,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_personality_result PRIMARY KEY (id),
    CONSTRAINT fk_personality_result_anonymous_user FOREIGN KEY (anonymous_user_id)
        REFERENCES anonymous_user (id),
    CONSTRAINT fk_personality_result_type FOREIGN KEY (type_code)
        REFERENCES personality_type (code),
    CONSTRAINT chk_personality_result_axis_scores CHECK (
        jsonb_typeof(axis_scores) = 'object' AND
        axis_scores ?& ARRAY['APOLOGY_SINCERITY', 'FAULT_STANDARD', 'PRINCIPLE_RELATION', 'ORDER_OPPORTUNITY'] AND
        jsonb_typeof(axis_scores->'APOLOGY_SINCERITY') = 'number' AND
        jsonb_typeof(axis_scores->'FAULT_STANDARD') = 'number' AND
        jsonb_typeof(axis_scores->'PRINCIPLE_RELATION') = 'number' AND
        jsonb_typeof(axis_scores->'ORDER_OPPORTUNITY') = 'number' AND
        (axis_scores->>'APOLOGY_SINCERITY')::numeric BETWEEN 0 AND 1 AND
        (axis_scores->>'FAULT_STANDARD')::numeric BETWEEN 0 AND 1 AND
        (axis_scores->>'PRINCIPLE_RELATION')::numeric BETWEEN 0 AND 1 AND
        (axis_scores->>'ORDER_OPPORTUNITY')::numeric BETWEEN 0 AND 1
    ),
    CONSTRAINT chk_personality_result_answers CHECK (jsonb_typeof(answers) = 'array')
);
-- 익명 사용자마다 현재 결과는 최대 한 건. 과거 응시 결과는 계속 보존한다.
CREATE UNIQUE INDEX ux_personality_result_current_user
    ON personality_result (anonymous_user_id) WHERE is_current;
CREATE INDEX ix_personality_result_user_created
    ON personality_result (anonymous_user_id, created_at DESC);

CREATE TABLE experience_personality (
    id            bigint      GENERATED BY DEFAULT AS IDENTITY,
    experience_id bigint      NOT NULL,
    axis_counts   jsonb       NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_experience_personality PRIMARY KEY (id),
    CONSTRAINT uk_experience_personality_experience UNIQUE (experience_id),
    CONSTRAINT fk_experience_personality_experience FOREIGN KEY (experience_id)
        REFERENCES experience (id),
    CONSTRAINT chk_experience_personality_axis_counts CHECK (
        jsonb_typeof(axis_counts) = 'object' AND
        axis_counts ?& ARRAY['APOLOGY_SINCERITY', 'FAULT_STANDARD', 'PRINCIPLE_RELATION', 'ORDER_OPPORTUNITY'] AND
        jsonb_typeof(axis_counts->'APOLOGY_SINCERITY') = 'object' AND
        jsonb_typeof(axis_counts->'APOLOGY_SINCERITY'->'down') = 'number' AND
        jsonb_typeof(axis_counts->'APOLOGY_SINCERITY'->'up') = 'number' AND
        (axis_counts->'APOLOGY_SINCERITY'->>'down')::numeric >= 0 AND
        (axis_counts->'APOLOGY_SINCERITY'->>'up')::numeric >= 0 AND
        (axis_counts->'APOLOGY_SINCERITY'->>'down')::numeric = trunc((axis_counts->'APOLOGY_SINCERITY'->>'down')::numeric) AND
        (axis_counts->'APOLOGY_SINCERITY'->>'up')::numeric = trunc((axis_counts->'APOLOGY_SINCERITY'->>'up')::numeric) AND
        jsonb_typeof(axis_counts->'FAULT_STANDARD') = 'object' AND
        jsonb_typeof(axis_counts->'FAULT_STANDARD'->'down') = 'number' AND
        jsonb_typeof(axis_counts->'FAULT_STANDARD'->'up') = 'number' AND
        (axis_counts->'FAULT_STANDARD'->>'down')::numeric >= 0 AND
        (axis_counts->'FAULT_STANDARD'->>'up')::numeric >= 0 AND
        (axis_counts->'FAULT_STANDARD'->>'down')::numeric = trunc((axis_counts->'FAULT_STANDARD'->>'down')::numeric) AND
        (axis_counts->'FAULT_STANDARD'->>'up')::numeric = trunc((axis_counts->'FAULT_STANDARD'->>'up')::numeric) AND
        jsonb_typeof(axis_counts->'PRINCIPLE_RELATION') = 'object' AND
        jsonb_typeof(axis_counts->'PRINCIPLE_RELATION'->'down') = 'number' AND
        jsonb_typeof(axis_counts->'PRINCIPLE_RELATION'->'up') = 'number' AND
        (axis_counts->'PRINCIPLE_RELATION'->>'down')::numeric >= 0 AND
        (axis_counts->'PRINCIPLE_RELATION'->>'up')::numeric >= 0 AND
        (axis_counts->'PRINCIPLE_RELATION'->>'down')::numeric = trunc((axis_counts->'PRINCIPLE_RELATION'->>'down')::numeric) AND
        (axis_counts->'PRINCIPLE_RELATION'->>'up')::numeric = trunc((axis_counts->'PRINCIPLE_RELATION'->>'up')::numeric) AND
        jsonb_typeof(axis_counts->'ORDER_OPPORTUNITY') = 'object' AND
        jsonb_typeof(axis_counts->'ORDER_OPPORTUNITY'->'down') = 'number' AND
        jsonb_typeof(axis_counts->'ORDER_OPPORTUNITY'->'up') = 'number' AND
        (axis_counts->'ORDER_OPPORTUNITY'->>'down')::numeric >= 0 AND
        (axis_counts->'ORDER_OPPORTUNITY'->>'up')::numeric >= 0 AND
        (axis_counts->'ORDER_OPPORTUNITY'->>'down')::numeric = trunc((axis_counts->'ORDER_OPPORTUNITY'->>'down')::numeric) AND
        (axis_counts->'ORDER_OPPORTUNITY'->>'up')::numeric = trunc((axis_counts->'ORDER_OPPORTUNITY'->>'up')::numeric)
    )
);
