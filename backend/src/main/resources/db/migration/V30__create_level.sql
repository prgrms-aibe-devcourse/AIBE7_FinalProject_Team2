-- V30__create_level.sql
-- 레벨 · 직업 (BE-106, docs/decisions/BE-106.md). 익명 사용자 단위(출석 · 체험 · 업적과 같은 기준).
--
-- xp_event: 이벤트로 들어오는 경험치의 원장. 한 줄 = 한 번의 지급.
--   사건 완료 · 성향 테스트 · 출석 · 업적 XP는 기존 테이블에서 그때그때 계산하므로 여기에 넣지 않는다.
--   source: POST · SHARE_POST · COMMENT · LIKE_GIVEN · LIKE_RECEIVED · SNS_SHARE (XpSource)
--   ref_key: 지급 대상(글 ID · 사건 ID 등). (사용자, source, ref_key)가 유니크라 같은 대상으로 두 번 받지 않는다
--   group_key: 대상별 상한을 세는 묶음(좋아요 받기는 글 ID). 없으면 빈 문자열
--   awarded_on: 일일 상한을 세는 KST 날짜
-- profile_job: 사용자가 카드에 보여 주려고 고른 직업. 없으면 해금된 가장 높은 직업을 보여 준다.
-- 새 테이블만 만든다(BE-60 "main으로 가는 마이그레이션은 추가만").
CREATE TABLE xp_event (
    id                bigint      GENERATED BY DEFAULT AS IDENTITY,
    anonymous_user_id uuid        NOT NULL,
    source            varchar(20) NOT NULL,
    ref_key           varchar(80) NOT NULL,
    group_key         varchar(80) NOT NULL DEFAULT '',
    amount            int         NOT NULL,
    awarded_on        date        NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_xp_event PRIMARY KEY (id),
    CONSTRAINT fk_xp_event_anonymous_user FOREIGN KEY (anonymous_user_id) REFERENCES anonymous_user (id),
    CONSTRAINT uq_xp_event_ref UNIQUE (anonymous_user_id, source, ref_key),
    CONSTRAINT chk_xp_event_source CHECK (source IN ('POST', 'SHARE_POST', 'COMMENT', 'LIKE_GIVEN', 'LIKE_RECEIVED', 'SNS_SHARE')),
    CONSTRAINT chk_xp_event_amount CHECK (amount > 0)
);

-- 일일 상한 · 묶음 상한 개수 세기
CREATE INDEX ix_xp_event_day ON xp_event (anonymous_user_id, source, awarded_on);
CREATE INDEX ix_xp_event_group ON xp_event (anonymous_user_id, source, group_key);

CREATE TABLE profile_job (
    anonymous_user_id uuid        NOT NULL,
    job               varchar(30) NOT NULL,
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_profile_job PRIMARY KEY (anonymous_user_id),
    CONSTRAINT fk_profile_job_anonymous_user FOREIGN KEY (anonymous_user_id) REFERENCES anonymous_user (id),
    CONSTRAINT chk_profile_job_job CHECK (job IN ('NONE', 'LAW_STUDENT', 'TRAINEE', 'PROBATION_JUDGE', 'JUDGE', 'PRESIDING_JUDGE',
        'HIGH_COURT_JUDGE', 'DISTRICT_COURT_CHIEF', 'HIGH_COURT_CHIEF', 'JUSTICE', 'CHIEF_JUSTICE'))
);
