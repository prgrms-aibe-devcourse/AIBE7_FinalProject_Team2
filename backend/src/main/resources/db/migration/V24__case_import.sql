-- V24__case_import.sql
-- 사건 등록 작업 (BE-93, API 명세 A-14 · A-15). 관리자가 판결문을 넣으면 백엔드가 AI 판결 파이프라인
-- 서비스(COMMON-50)에 작업을 맡기고, 그 진행 상황을 이 표로 추적한다. 파이프라인은 수십 분 걸려서
-- 요청을 기다리지 않고(202) 화면이 2초마다 A-15로 묻는다.
--
-- 왜 원문을 여기에 두는가
--   파이프라인 서비스는 **판결문 원문을 결과로 돌려주지 않는다**(요구사항 FR-5-3, COMMON-50).
--   그런데 적재 대상인 case_source.original_text에는 원문이 들어가야 한다. 그 원문을 다시 받아오려고
--   서비스 쪽 경계를 무르게 만드는 대신, A-14에서 이미 받은 원문을 백엔드가 그대로 들고 있다가
--   적재할 때 case_source로 옮긴다. 원문을 아는 쪽이 원래부터 백엔드이기 때문이다.
--   적재가 끝나면 case_source에 같은 원문이 생기므로, 2차 PR에서 이 표의 original_text를 비운다
--   (두 벌로 남겨 두지 않는다).
CREATE TABLE case_import (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY,
    -- 파이프라인 서비스의 작업 ID (32자리 16진수). 상태 조회 · 정리에 쓴다
    job_id      varchar(32) NOT NULL,
    status      varchar(20) NOT NULL,
    crime_type  varchar(20) NOT NULL,
    -- 적재가 끝나면 채워진다 (2차 PR). 1차 범위에서는 SUCCEEDED여도 NULL이다
    case_id     bigint,
    error_code  varchar(50),
    -- 실패 사유. 원문 · 모델 출력을 담지 않는다 (API 명세 A-15)
    message     varchar(500),
    -- 파이프라인에서 마지막으로 받은 단계 상태 ([{"name":"extract","status":"DONE"}, ...]).
    -- 단계별 상태를 아는 쪽은 파이프라인뿐인데, 끝난 작업은 더 묻지 않고 화면은 다시 열릴 수 있다.
    -- 그때 사실과 다른 값을 보여주지 않으려고 받아 둔다
    stages      jsonb,
    created_at  timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    CONSTRAINT pk_case_import PRIMARY KEY (id),
    CONSTRAINT fk_case_import_legal_case FOREIGN KEY (case_id) REFERENCES legal_case (id),
    CONSTRAINT uk_case_import_job_id UNIQUE (job_id),
    CONSTRAINT chk_case_import_status CHECK (status IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT chk_case_import_crime_type CHECK (crime_type IN ('MURDER', 'FRAUD', 'INJURY'))
);

-- 진행 중인 등록이 있는지 확인한다 (A-14 IMPORT_IN_PROGRESS). 한 번에 하나만 돌린다
CREATE INDEX idx_case_import_status ON case_import (status);

-- 등록 요청에 들어온 판결문. 적재 때 case_source로 옮기므로 컬럼을 그 표와 맞춰 둔다.
-- case_source와 달리 source_org는 NULL을 받는다 — A-14에서 선택 값이고, 적재할 때 기본값을 채운다
CREATE TABLE case_import_source (
    id            bigint      GENERATED BY DEFAULT AS IDENTITY,
    import_id     bigint      NOT NULL,
    court_level   varchar(20) NOT NULL,
    case_number   varchar(50) NOT NULL,
    court_name    varchar(50),
    decided_at    date,
    is_final      boolean     NOT NULL,  -- 최종 확정 판결 여부
    source_org    varchar(50),
    -- 판결문 원문. 적재가 끝나면 비운다 (위 머리말 참고)
    original_text text,
    note          text,
    -- 요청에 들어온 순서 (심급 순서와 다를 수 있다)
    display_order int         NOT NULL,
    CONSTRAINT pk_case_import_source PRIMARY KEY (id),
    CONSTRAINT fk_case_import_source_case_import FOREIGN KEY (import_id) REFERENCES case_import (id) ON DELETE CASCADE,
    CONSTRAINT chk_case_import_source_court_level CHECK (court_level IN ('FIRST', 'APPEAL', 'SUPREME')),
    -- 한 등록 안에서 심급은 서로 달라야 한다 (A-14 검증과 같은 조건을 DB에서도 지킨다)
    CONSTRAINT uk_case_import_source_level UNIQUE (import_id, court_level)
);

-- 한 등록에서 최종 확정 판결은 1건 (case_source의 uk_case_source_final과 같은 규칙, V6).
-- A-14에서도 막지만, 적재 대상 표와 같은 조건을 여기서도 지켜 두 표가 어긋나지 않게 한다
CREATE UNIQUE INDEX uk_case_import_source_final ON case_import_source (import_id) WHERE is_final = TRUE;

CREATE INDEX idx_case_import_source_import_id ON case_import_source (import_id);
-- 이미 등록한 사건번호인지 볼 때 쓴다 (A-14 DUPLICATE_SOURCE는 case_source를 보지만,
-- 진행 중인 등록과 겹치는지도 함께 본다)
CREATE INDEX idx_case_import_source_case_number ON case_import_source (case_number);

