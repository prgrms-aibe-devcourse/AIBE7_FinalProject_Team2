ALTER TABLE case_script DROP CONSTRAINT chk_case_script_review_note;
ALTER TABLE case_script DROP CONSTRAINT chk_case_script_review_status;
ALTER TABLE case_script DROP CONSTRAINT fk_case_script_admin;
ALTER TABLE case_script DROP COLUMN evidence;
ALTER TABLE case_script DROP COLUMN review_status;
ALTER TABLE case_script DROP COLUMN reviewed_by_admin_id;
ALTER TABLE case_script DROP COLUMN reviewed_at;
