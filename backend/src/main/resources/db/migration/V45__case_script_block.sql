-- V45__case_script_block.sql
-- 사건 대본을 단위 블록(U0 ~ U4)으로 저장한다 (BE-126 1차). 블록마다 내용 · 판 · 생성 근거 · 검수 결과 · 검수 상태를 둔다.
--
-- 블록을 행으로 나누는 이유: 단위마다 따로 검수 · 승인하고(2차), 한 블록만 다시 만들 수 있어야 한다(BE-129). 한 칸
-- jsonb에 블록을 모두 담으면 블록 하나를 고칠 때 다른 블록의 검수 상태까지 함께 다시 써야 하고, "오류 있는 블록은
-- 승인할 수 없다"를 DB 제약으로 걸 수 없다. 블록 안의 내용은 V32와 같은 이유로 jsonb 한 칸이다(형식은 파이프라인이 정한다).
--
-- 블록 형식 · 생성 근거(basis)의 계약: tools/ai-judgment/prompts/script/README.md "저장 블록",
-- 연동 표 정본: tools/ai-judgment/contracts/script_blocks.json (결정: docs/decisions/BE-126.md)

-- 사건 내용 · 기사의 판. 블록의 basis가 "어느 판을 보고 만들었는지"를 이 값으로 남긴다(낡음 계산은 2차).
-- updated_at을 쓰지 않는 이유: 공개 상태 변경 · 사진 같은, 대본 입력이 아닌 수정에도 바뀌어 낡음이 잘못 뜬다.
-- 대본 입력(제목 · 개요 · 기사 본문)을 고칠 때만 올린다
ALTER TABLE legal_case ADD COLUMN content_revision integer NOT NULL DEFAULT 1;
ALTER TABLE case_paper ADD COLUMN revision integer NOT NULL DEFAULT 1;

CREATE TABLE case_script_block (
    id                   bigint       GENERATED BY DEFAULT AS IDENTITY,
    script_id            bigint       NOT NULL,
    unit                 varchar(2)   NOT NULL,    -- U0 설계도 · U1 1막 해설 · U2 재판 도입부 · U3 증거조사 · U4 3막
    -- 블록 값. U3는 증거조사 대사 배열(만들지 못한 줄은 text가 null), 나머지는 객체다. 검수 결과의 path가 이 값을 가리킨다
    content              jsonb        NOT NULL,
    revision             integer      NOT NULL DEFAULT 1,   -- 판. 고쳐 쓰기 · 수정으로 값이 바뀔 때마다 오른다
    -- 만들 때 본 값(앞 블록은 판, 분류 · 배역은 값, 사건 내용 · 기사는 위 판). 지금 값과 다르면 낡은 블록이다
    basis                jsonb        NOT NULL DEFAULT '{}'::jsonb,
    -- 아래 셋은 관리자 화면 전용이다 — 고치기 전 문장과 대본 인용이 들어 있어 공개 API(API 18)에 싣지 않는다
    review               jsonb        NOT NULL DEFAULT '[]'::jsonb,   -- 검수 조건 결과(BE-122) 중 이 블록 것
    warnings             jsonb        NOT NULL DEFAULT '[]'::jsonb,   -- 단위 형식 경고(U3는 줄마다 validation에 있다)
    repairs              jsonb        NOT NULL DEFAULT '[]'::jsonb,   -- 고쳐 쓰기 기록(BE-122 2차) 중 이 블록 것
    -- 오류 없이 공개할 수 있는 블록인지. false면 승인할 수 없다(아래 제약). 적재 · 수정할 때 서버가 계산한다
    publishable          boolean      NOT NULL,
    -- 검수 상태. V32와 같이 APPROVED · REJECTED만 저장하고 비어 있으면 대기로 읽는다
    review_status        varchar(20),
    reviewed_by_admin_id bigint,
    reviewed_at          timestamptz,
    review_note          varchar(500),
    created_at           timestamptz  NOT NULL DEFAULT now(),
    updated_at           timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_case_script_block PRIMARY KEY (id),
    -- 대본을 지우면 블록도 지운다(블록은 대본 없이 의미가 없다)
    CONSTRAINT fk_case_script_block_script FOREIGN KEY (script_id) REFERENCES case_script (id) ON DELETE CASCADE,
    CONSTRAINT fk_case_script_block_admin FOREIGN KEY (reviewed_by_admin_id) REFERENCES admin_account (id) ON DELETE SET NULL,
    CONSTRAINT uk_case_script_block_unit UNIQUE (script_id, unit),
    CONSTRAINT chk_case_script_block_unit CHECK (unit IN ('U0', 'U1', 'U2', 'U3', 'U4')),
    CONSTRAINT chk_case_script_block_revision CHECK (revision >= 1),
    CONSTRAINT chk_case_script_block_review_status CHECK (review_status IS NULL OR review_status IN ('APPROVED', 'REJECTED')),
    -- 오류 있는 블록은 승인할 수 없다 (V32 chk_case_script_publishable_approved를 블록으로 옮긴 것)
    CONSTRAINT chk_case_script_block_publishable_approved CHECK (review_status <> 'APPROVED' OR publishable),
    CONSTRAINT chk_case_script_block_review_note CHECK (review_note IS NULL OR review_status = 'REJECTED')
);

-- 대본 메타 · 대본 전체 값.
-- issue: 분류 쟁점(admitted · denied …). 프론트 공통 틀이 신문 마지막 질문을 고른다. 값 목록은 파이프라인이 정해 CHECK를
--        걸지 않는다(V37 sensitive_flags와 같은 이유). 분류 없이 만든 대본(증거조사만)은 비어 있다
-- admits: 피고인이 혐의를 인정하는지(U0 세 번째 답). 마지막 답 "…네, 인정합니다." / "…아닙니다."를 고른다. U0가 없으면 비어 있다
-- pending: 파이프라인이 만들지 못한 단위(["U1"] 등). 하나라도 있으면 대본 전체를 승인할 수 없다
-- review: 대본 전체에 걸린 검수 결과(REVIEW_FAILED — 검사 자체가 돌지 못함). 블록 것은 블록 행에 있다
ALTER TABLE case_script ADD COLUMN issue varchar(30);
ALTER TABLE case_script ADD COLUMN admits boolean;
ALTER TABLE case_script ADD COLUMN pending jsonb NOT NULL DEFAULT '[]'::jsonb;
ALTER TABLE case_script ADD COLUMN review jsonb NOT NULL DEFAULT '[]'::jsonb;

-- 기존 대본(증거조사 대사뿐, BE-108)은 U3 블록 하나로 옮긴다. 운영은 0행이라(2026-10-30 확인) 개발 · 로컬 DB용이다.
-- 검수 상태는 대본의 것을 그대로 옮긴다 — 승인한 대본은 승인한 U3 하나라 공개 여부가 바뀌지 않는다.
-- 블록의 공개 가능 여부는 대본의 값을 쓴다(대사뿐인 대본은 둘이 같은 식이다: 멈추지 않았고 빈 줄이 없다).
-- 생성 근거는 적재(증거조사만 만든 대본)와 같게 아는 값만 남긴다 — 사건 내용 판(위에서 1로 시작)과 배역
INSERT INTO case_script_block (script_id, unit, content, basis, publishable, review_status, reviewed_by_admin_id,
                               reviewed_at, review_note, created_at, updated_at)
SELECT id, 'U3', evidence, jsonb_build_object('case', 1, 'cast', cast_roles), publishable, review_status,
       reviewed_by_admin_id, reviewed_at, review_note, created_at, updated_at
FROM case_script;

