-- V47__case_script_regeneration.sql
-- 대본 블록 재생성 작업 (BE-129 2차-2). 관리자가 고른 블록을 파이프라인 서비스에 다시 만들게 하고(A-13-15), 진행 상황을 받아
-- 적고(A-13-16), 끝난 결과를 관리자가 반영한다(A-13-17). 사건 등록(case_import, V24)과 같은 흐름이다.
--
-- 대본(case_script)에 칸을 더하지 않고 행으로 두는 이유: 재생성은 한 사건에 여러 번 일어나고, 누가 무엇을 다시 만들었는지 남아야
-- 한다. 반영하지 않고 버린 작업도 남는다(반영할 수 있는 것은 그 사건의 가장 최근 작업뿐이다).
--
-- 결정: docs/decisions/BE-129.md "2차-2"

CREATE TABLE case_script_regeneration (
    id                    bigint       GENERATED BY DEFAULT AS IDENTITY,
    case_id               bigint       NOT NULL,
    job_id                varchar(32)  NOT NULL,     -- 파이프라인 서비스 작업 ID (32자리 16진수)
    units                 jsonb        NOT NULL,     -- 관리자가 고른 블록 (예: ["U4"])
    cascade_later         boolean      NOT NULL,     -- 그 블록을 입력으로 받는 뒤 블록도 함께 만드는지 (false = 세부조정)
    -- 요청 당시 입력 {blocks: {단위: 판}, case, paper, cast, classification, sensitiveFlags}. 반영할 때 지금 값과 비교해
    -- 다르면 거절한다 — 그 사이 대사를 고치거나 다른 재생성을 반영했으면 옛 입력으로 만든 블록이 들어가기 때문이다
    inputs                jsonb        NOT NULL,
    status                varchar(20),               -- QUEUED · RUNNING · SUCCEEDED · FAILED (처음 진행 상황을 받을 때 채운다)
    error_code            varchar(50),
    message               varchar(500),              -- 실패 사유 (원문 · 모델 출력은 담지 않는다)
    stages                jsonb,                     -- 마지막으로 받은 단계 상태 [{name, status}]
    requested_by_admin_id bigint,
    applied_by_admin_id   bigint,
    applied_at            timestamptz,               -- 결과를 블록에 반영한 시각. 반영하지 않은 작업은 null
    created_at            timestamptz  NOT NULL DEFAULT now(),
    finished_at           timestamptz,
    CONSTRAINT pk_case_script_regeneration PRIMARY KEY (id),
    -- 사건을 지우면 재생성 기록도 지운다 (대본 · 블록과 같다)
    CONSTRAINT fk_case_script_regeneration_case FOREIGN KEY (case_id) REFERENCES legal_case (id) ON DELETE CASCADE,
    CONSTRAINT fk_case_script_regeneration_requested FOREIGN KEY (requested_by_admin_id) REFERENCES admin_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_case_script_regeneration_applied FOREIGN KEY (applied_by_admin_id) REFERENCES admin_account (id) ON DELETE SET NULL,
    CONSTRAINT uk_case_script_regeneration_job_id UNIQUE (job_id),
    CONSTRAINT chk_case_script_regeneration_status CHECK (status IS NULL OR status IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT chk_case_script_regeneration_applied CHECK (applied_at IS NULL OR status = 'SUCCEEDED')
);

-- 사건의 가장 최근 작업 · 진행 중인 작업을 찾는다
CREATE INDEX idx_case_script_regeneration_case ON case_script_regeneration (case_id, id DESC);

