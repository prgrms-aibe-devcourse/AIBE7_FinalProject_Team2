-- V19__case_incident_photo.sql
-- 사건 발단 사진 (BE-91, COMMON-41). Cloudflare Workers AI로 생성해 S3에 올린 사진 여러 장을
-- 사건 하나에 순서대로 붙인다. 사건 대표사진(신문용)은 새 테이블을 두지 않고 기존 legal_case.thumbnail_url을
-- 그대로 쓴다(관리자가 이미 A-11로 자유롭게 바꿀 수 있던 칸이라 재사용, docs/decisions/BE-91.md).
CREATE TABLE case_incident_photo (
    id            bigint       GENERATED BY DEFAULT AS IDENTITY,
    case_id       bigint       NOT NULL,
    image_url     varchar(500) NOT NULL,  -- 프론트에 내려주는 공개 URL (S3 또는 CDN)
    s3_key        varchar(300) NOT NULL,  -- S3 객체 키 (재생성 · 삭제 때 사용, 공개 응답에는 내려주지 않는다)
    caption       varchar(200),
    prompt        text         NOT NULL,  -- 생성에 쓴 프롬프트 원문 (감사 · 재생성용, CaseImagePromptBuilder 결과)
    model         varchar(100) NOT NULL,  -- 생성에 쓴 Cloudflare Workers AI 모델 (예: @cf/black-forest-labs/flux-1-schnell)
    display_order int          NOT NULL,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_case_incident_photo PRIMARY KEY (id),
    CONSTRAINT fk_case_incident_photo_legal_case FOREIGN KEY (case_id) REFERENCES legal_case (id),
    CONSTRAINT uk_case_incident_photo_case_display_order UNIQUE (case_id, display_order)
);

-- case_id는 유니크 제약의 첫 컬럼이라 별도 인덱스 생략

-- 관리자 감사 로그(V14)에 사진 생성 행동을 추가한다. CHECK는 드롭 후 다시 만들어야 한다(Postgres는 CHECK를 직접 못 바꾼다)
ALTER TABLE admin_audit_log DROP CONSTRAINT chk_admin_audit_log_action;
ALTER TABLE admin_audit_log ADD CONSTRAINT chk_admin_audit_log_action CHECK (action IN (
    'LOGIN_SUCCESS', 'LOGIN_FAILURE', 'LOGOUT', 'SOURCE_VIEW',
    'JUDGMENT_APPROVE', 'JUDGMENT_REJECT', 'CASE_UPDATE', 'VALUE_AXIS_CONFIRM', 'CASE_PUBLISH',
    'CASE_PHOTO_GENERATE'));
